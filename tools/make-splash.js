#!/usr/bin/env node
/* iOS launch ("splash") images. Without them, a game opened from the iPhone/iPad Home Screen starts on a plain WHITE
   screen. This renders a dark one (icon + wordmark) for every current iPhone and iPad size and writes the
   <link rel="apple-touch-startup-image"> tags into index.html between the splash:start / splash:end markers.
   Usage: node tools/make-splash.js */
const fs=require('fs'), path=require('path');
const {chromium}=require('playwright');
const root=path.join(__dirname,'..'), outDir=path.join(root,'splash');

/* css width, css height (portrait), pixel ratio */
const IPHONES=[[440,956,3],[402,874,3],[430,932,3],[393,852,3],[428,926,3],[390,844,3],[375,812,3],[414,896,3],[414,896,2],[414,736,3],[375,667,2],[320,568,2]];
const IPADS=[[1024,1366,2],[1032,1376,2],[834,1194,2],[834,1210,2],[834,1112,2],[820,1180,2],[810,1080,2],[768,1024,2],[744,1133,2]];

const icon='data:image/png;base64,'+fs.readFileSync(path.join(root,'icons/icon-512.png')).toString('base64');
const page=(w,h)=>`<!doctype html><meta charset="utf-8"><style>
  html,body{margin:0;width:${w}px;height:${h}px;background:#14102b;overflow:hidden}
  body{display:flex;flex-direction:column;align-items:center;justify-content:center;gap:${Math.round(Math.min(w,h)*.045)}px;font-family:ui-rounded,"SF Pro Rounded",Nunito,system-ui,sans-serif}
  img{width:${Math.round(Math.min(w,h)*.3)}px;height:auto;border-radius:22%}
  .logo{display:flex;flex-direction:column;align-items:center;line-height:.86;font-size:${Math.round(Math.min(w,h)*.11)}px;font-weight:900;letter-spacing:-.03em}
  .logo span:first-child{background:linear-gradient(180deg,#fff,#ffd36b);-webkit-background-clip:text;background-clip:text;color:transparent}
  .logo span:last-child{background:linear-gradient(180deg,#ff8ad0,#7c5cff);-webkit-background-clip:text;background-clip:text;color:transparent}
</style><img src="${icon}"><div class="logo"><span>STACK</span><span>RUSH</span></div>`;

(async()=>{
  fs.mkdirSync(outDir,{recursive:true});
  for(const f of fs.readdirSync(outDir)) if(f.endsWith('.png')) fs.unlinkSync(path.join(outDir,f));
  const b=await chromium.launch(); const links=[]; let bytes=0;
  const jobs=[];
  for(const [w,h,r] of IPHONES) jobs.push([w,h,r,'portrait']);
  for(const [w,h,r] of IPADS){ jobs.push([w,h,r,'portrait']); jobs.push([h,w,r,'landscape']); }
  for(const [w,h,r,orient] of jobs){
    const ctx=await b.newContext({viewport:{width:w,height:h},deviceScaleFactor:r}); const p=await ctx.newPage();
    await p.setContent(page(w,h)); const name=`splash-${w*r}x${h*r}.png`;
    const buf=await p.screenshot({path:path.join(outDir,name),type:'png'}); bytes+=buf.length; await ctx.close();
    /* media queries always use the portrait device-width/device-height pair */
    const [dw,dh]=orient==='portrait'?[w,h]:[h,w];
    links.push(`<link rel="apple-touch-startup-image" href="splash/${name}" media="(device-width: ${dw}px) and (device-height: ${dh}px) and (-webkit-device-pixel-ratio: ${r}) and (orientation: ${orient})">`);
  }
  await b.close();
  const file=path.join(root,'index.html'); let html=fs.readFileSync(file,'utf8');
  const block='<!-- splash:start (generated by tools/make-splash.js) -->\n'+links.join('\n')+'\n<!-- splash:end -->';
  if(html.includes('<!-- splash:start')) html=html.replace(/<!-- splash:start[\s\S]*?<!-- splash:end -->/,block);
  else html=html.replace('<title>Stack Rush</title>',block+'\n<title>Stack Rush</title>');
  fs.writeFileSync(file,html);
  console.log(`${jobs.length} launch images, ${(bytes/1024/1024).toFixed(2)} MB total, links written to index.html`);
})();
